export function Segmented({ value, options, onChange }) {
  return (
    <div className="segmented">
      {options.map(([v, l]) => (
        <button key={v} className={value === v ? 'on' : ''} onClick={() => onChange(v)}>{l}</button>
      ))}
    </div>
  )
}
